import bcrypt

from business_object.user import User
from dao.db_connection import DBConnection
from utils.log_utils import get_logger, log
from utils.singleton import Singleton

logger = get_logger(__name__)


class UserDao(metaclass=Singleton):
    """
    Class containing methods to access Users in the database.
    """

    ROUND = 12

    @staticmethod
    def hash_pw(password: str) -> str:
        """
        Hash the password.

        Parameters
        ----------
        password : str
            User's password

        Return
        ------
        str
            The bcrypt hash of a password.
        """
        hashed = bcrypt.hashpw(password.encode("utf-8"), bcrypt.gensalt(rounds=UserDao.ROUND))
        return hashed.decode("ascii")

    @staticmethod
    def verify_pw(password: str, hashed: str) -> bool:
        """
        Compare password given with the hashed registered one.
        Parameters
        ----------
        password : str
            User's password
        hashed : str
            The hashed password from the database

        Return
        ------
        Bool
            True if the password matches the hash.
        """
        try:
            return bcrypt.checkpw(password.encode("utf-8"), hashed.encode("ascii"))
        except ValueError:  # malformed hash or password too long
            return False

    @log
    def create(self, user) -> bool:
        """
        Create a user in the database.

        The identifier generated by the database is set on ``user``.

        Parameters
        ----------
        user : User
            User to create.

        Returns
        -------
        bool
            True if creation is successful, False otherwise.
        """
        res = None

        try:
            with DBConnection().connection as connection:
                with connection.cursor() as cursor:
                    cursor.execute(
                        "INSERT INTO user_table(username, password, email) VALUES "
                        "(%(username)s, %(password)s, %(email)s) "
                        "RETURNING id_user;",
                        {
                            "username": user.username,
                            "password": user.password,
                            "email": user.email,
                        },
                    )
                    res = cursor.fetchone()
        except Exception as e:
            logger.error(e)
            raise

        created = False
        if res:
            user.id_user = res["id_user"]
            created = True

        return created

    @log
    def find_by_id(self, id_user: int) -> User:
        """
        Find a user by their identifier.

        Parameters
        ----------
        id_user : int
            Identifier of the user to find.

        Returns
        -------
        User or None
            User matching the given identifier, or None if not found.
        """
        try:
            with DBConnection().connection as connection:
                with connection.cursor() as cursor:
                    cursor.execute(
                        "SELECT *                            "
                        "  FROM user_table                   "
                        " WHERE id_user = %(id_user)s;   ",
                        {"id_user": id_user},
                    )
                    res = cursor.fetchone()
        except Exception as e:
            logger.error(e)
            raise

        user = None
        if res:
            user = User(
                username=res["username"],
                email=res["email"],
                id_user=res["id_user"],
                password=res["password"],
            )

        return user

    @log
    def find_all(self) -> list[User]:
        """
        List all users in the database.

        Returns
        -------
        list of User
            All users, sorted by username.
        """

        try:
            with DBConnection().connection as connection:
                with connection.cursor() as cursor:
                    cursor.execute(
                        "SELECT *                                "
                        "  FROM user_table                       "
                        " ORDER BY username;                     "
                    )
                    res = cursor.fetchall()
        except Exception as e:
            logger.error(e)
            raise

        users_list = []

        if res:
            for row in res:
                user = User(
                    id_user=row["id_user"],
                    username=row["username"],
                    password=row["password"],
                    email=row["email"],
                )

                users_list.append(user)

        return users_list

    @log
    def update(self, user) -> bool:
        """
        Update a user in the database.

        Password and access token are kept unchanged if they are None.

        Parameters
        ----------
        user : User
            User to update.

        Returns
        -------
        bool
            True if update is successful, False otherwise.
        """
        nb_affected_rows = 0

        try:
            with DBConnection().connection as connection:
                with connection.cursor() as cursor:
                    cursor.execute(
                        "UPDATE user_table                                                  "
                        "   SET username = %(username)s,                                "
                        "       password = COALESCE(%(password)s, password),            "
                        "       email = %(email)s,                                      "
                        "       access_token = COALESCE(%(access_token)s, access_token) "
                        " WHERE id_user = %(id_user)s;                              ",
                        {
                            "username": user.username,
                            "password": user.password,
                            "email": user.email,
                            "access_token": user.access_token,
                            "id_user": user.id_user,
                        },
                    )
                    nb_affected_rows = cursor.rowcount
        except Exception as e:
            logger.error(e)
            raise

        return nb_affected_rows == 1

    @log
    def delete(self, user) -> bool:
        """
        Delete a user from the database.

        Parameters
        ----------
        user : User
            User to delete.

        Returns
        -------
        bool
            True if the user was successfully deleted, False otherwise.
        """
        try:
            with DBConnection().connection as connection:
                with connection.cursor() as cursor:
                    cursor.execute(
                        "DELETE FROM user_table                       "
                        " WHERE id_user = %(id_user)s                 ",
                        {"id_user": user.id_user},
                    )
                    res = cursor.rowcount
        except Exception as e:
            logger.error(e)
            raise

        return res > 0

    @log
    def login(self, username: str, password: str) -> User:
        """
        Find the user matching a username and a password.

        Parameters
        ----------
        username : str
            Username of the user.
        password : str
            Password of the user.

        Returns
        -------
        User or None
            The matching user, or None if the credentials are invalid.
        """
        res = None
        try:
            with DBConnection().connection as connection:
                with connection.cursor() as cursor:
                    cursor.execute(
                        "SELECT *                               "
                        "  FROM user_table                      "
                        " WHERE username = %(username)s         "
                        "   AND password = %(password)s;        ",
                        {"username": username, "password": password},
                    )
                    res = cursor.fetchone()
        except Exception as e:
            logger.error(e)
            raise

        user = None

        if res:
            user = User(
                username=res["username"],
                password=res["password"],
                email=res["email"],
                access_token=res["access_token"],
                id_user=res["id_user"],
            )

        return user

    @log
    def find_by_token(self, access_token: str) -> User:
        """
        Find a user by their access token.

        Parameters
        ----------
        access_token : str
            Token to search for.

        Returns
        -------
        User or None
            User matching the token, or None if not found or if the token
            is empty.
        """
        if not access_token:
            return None

        res = None
        try:
            with DBConnection().connection as connection:
                with connection.cursor() as cursor:
                    cursor.execute(
                        "SELECT *                                "
                        "  FROM user_table                       "
                        " WHERE access_token = %(token)s;        ",
                        {"token": access_token},
                    )
                    res = cursor.fetchone()
        except Exception as e:
            logger.error(f"Error finding user by token: {e}")
            raise

        user = None
        if res:
            user = User(
                id_user=res["id_user"],
                username=res["username"],
                password=res["password"],
                email=res["email"],
                access_token=res["access_token"],
            )

        return user

